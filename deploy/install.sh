#!/usr/bin/env bash
# Ciro one-command server install / upgrade (Linux, Docker).
#
#   curl -fsSL https://github.com/kllcoco/frontend-UI/releases/latest/download/Server-install.sh | sudo bash
#   sudo bash install.sh            # install (asks a few questions)
#   sudo bash install.sh upgrade    # pull the newest image and restart, keeping data and settings
#   sudo bash install.sh uninstall  # stop and remove containers (data volume is kept)
#
# Non-interactive: set CIRO_API_BASE_URL, CIRO_MODEL, CIRO_API_KEY and optionally CIRO_DOMAIN before running.
# With a domain, Ciro runs with accounts enabled behind Caddy (automatic HTTPS). Without one it listens on
# port 8787 for use on a private network.
set -euo pipefail

DIR="${CIRO_DIR:-/opt/ciro}"
IMAGE="${CIRO_IMAGE:-ghcr.io/kllcoco/ciro-client}"
TAG="${CIRO_VERSION:-latest}"
DRY_RUN="${CIRO_DRY_RUN:-}"   # write files only (used by tests)
ACTION="${1:-install}"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }
ask() { # ask VAR "question" "default" [secret] — skipped when VAR is already set (even to empty)
  local var="$1" q="$2" def="${3:-}" secret="${4:-}" value=""
  if [ -n "${!var+x}" ]; then return; fi
  if ! { : </dev/tty; } 2>/dev/null; then printf -v "$var" '%s' "$def"; return; fi
  local prompt="$q"; [ -n "$def" ] && prompt="$q [$def]"
  if [ -n "$secret" ]; then read -r -s -p "$prompt: " value </dev/tty; echo; else read -r -p "$prompt: " value </dev/tty; fi
  printf -v "$var" '%s' "${value:-$def}"
}
secret() { openssl rand -base64 32 2>/dev/null || head -c 32 /dev/urandom | base64; }
compose() { (cd "$DIR" && docker compose "$@"); }

need_root() { [ -n "$DRY_RUN" ] || [ "$(id -u)" -eq 0 ] || die "Please run as root (sudo bash install.sh)."; }

ensure_docker() {
  [ -n "$DRY_RUN" ] && return
  if ! command -v docker >/dev/null 2>&1; then
    say "Installing Docker…"
    curl -fsSL https://get.docker.com | sh
  fi
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose)."
  systemctl enable --now docker >/dev/null 2>&1 || true
}

pull() {
  [ -n "$DRY_RUN" ] && return
  if ! compose pull; then
    warn "Could not pull $IMAGE:$TAG. If the package is private, log in first:"
    warn "  echo <token with read:packages> | docker login ghcr.io -u <github user> --password-stdin"
    exit 1
  fi
}

write_files() {
  mkdir -p "$DIR"
  local domain="$1"
  if [ -n "$domain" ]; then
    # Accounts mode must listen on loopback; Caddy on the host terminates HTTPS.
    cat >"$DIR/docker-compose.yml" <<EOF
services:
  ciro:
    image: $IMAGE:\${CIRO_VERSION:-$TAG}
    restart: unless-stopped
    network_mode: host
    env_file: .env
    environment:
      HOST: 127.0.0.1
      PORT: "8787"
    volumes:
      - ciro-data:/data
  caddy:
    image: caddy:2
    restart: unless-stopped
    network_mode: host
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config
volumes:
  ciro-data:
  caddy-data:
  caddy-config:
EOF
    cat >"$DIR/Caddyfile" <<EOF
$domain {
  encode zstd gzip
  reverse_proxy 127.0.0.1:8787
}
EOF
  else
    cat >"$DIR/docker-compose.yml" <<EOF
services:
  ciro:
    image: $IMAGE:\${CIRO_VERSION:-$TAG}
    restart: unless-stopped
    env_file: .env
    environment:
      HOST: 0.0.0.0
      PORT: "8787"
    ports:
      - "8787:8787"
    volumes:
      - ciro-data:/data
volumes:
  ciro-data:
EOF
  fi
}

install() {
  need_root
  [ -f "$DIR/.env" ] && { say "Existing installation found in $DIR — upgrading instead (settings kept)."; upgrade; return; }
  ensure_docker
  say "Model connection (OpenAI-compatible API)"
  ask CIRO_API_BASE_URL "API base URL, up to /v1" "https://api.example.com/v1"
  ask CIRO_MODEL "Default model" "ciro"
  ask CIRO_API_KEY "API key (stored only on this server)" "" secret
  ask CIRO_DOMAIN "Domain for HTTPS + accounts (leave empty for private network use)" ""
  local domain="${CIRO_DOMAIN#https://}"; domain="${domain%%/*}"
  mkdir -p "$DIR"; umask 077
  {
    echo "# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Edit, then: cd $DIR && docker compose up -d"
    echo "CIRO_API_BASE_URL=$CIRO_API_BASE_URL"
    echo "CIRO_MODEL=$CIRO_MODEL"
    echo "CIRO_API_KEY=$CIRO_API_KEY"
    echo "CIRO_WEB_SEARCH=off"
    echo "CIRO_VOICE=off"
    echo "CIRO_IMAGES=off"
    if [ -n "$domain" ]; then
      echo "CIRO_ACCOUNTS_ENABLED=true"
      echo "CIRO_PUBLIC_ORIGIN=https://$domain"
      echo "CIRO_BOOTSTRAP_TOKEN=$(secret)"
      echo "CIRO_API_KEY_PEPPER=$(secret)"
      echo "# Never change this key: encrypted account data depends on it."
      echo "CIRO_ACCOUNT_DATA_KEY=$(openssl rand -base64 32 2>/dev/null || head -c 32 /dev/urandom | base64)"
    fi
  } >"$DIR/.env"
  chmod 600 "$DIR/.env"
  write_files "$domain"
  pull
  [ -n "$DRY_RUN" ] || compose up -d
  echo
  if [ -n "$domain" ]; then
    say "Ciro is starting at https://$domain (certificate is issued automatically; DNS must point here, ports 80/443 open)."
    say "Create the owner account there with this bootstrap token:"
    grep '^CIRO_BOOTSTRAP_TOKEN=' "$DIR/.env" | cut -d= -f2-
  else
    say "Ciro is running at http://$(hostname -I 2>/dev/null | awk '{print $1}'):8787 — private network only (no login)."
  fi
  say "Settings: $DIR/.env   Upgrade: sudo bash install.sh upgrade"
}

upgrade() {
  need_root
  [ -f "$DIR/docker-compose.yml" ] || die "No installation in $DIR. Run: sudo bash install.sh"
  ensure_docker
  say "Pulling the newest Ciro image…"
  pull
  [ -n "$DRY_RUN" ] || { compose up -d; docker image prune -f >/dev/null 2>&1 || true; }
  say "Upgraded. Open pages will offer a refresh to load the new version."
}

uninstall() {
  need_root
  [ -f "$DIR/docker-compose.yml" ] || die "No installation in $DIR."
  [ -n "$DRY_RUN" ] || compose down
  say "Stopped. Data volumes and $DIR/.env are kept; remove them manually to erase everything."
}

case "$ACTION" in
  install) install ;;
  upgrade|update) upgrade ;;
  uninstall) uninstall ;;
  *) die "Usage: install.sh [install|upgrade|uninstall]" ;;
esac
